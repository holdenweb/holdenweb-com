#!/usr/bin/env python3
"""Regenerate `ops/records/still_to_do.md` from the open items in `backlog.md`.

`backlog.md` is the record: append-only, keeping fixed and struck items beside
the evidence that closed them, with stable numbers. That makes it the right
thing to keep and the wrong thing to read when you want to know what is left.
This extracts the latter without touching the former.

Nothing is hard-coded, deliberately. An earlier hand-made copy listed the open
numbers literally, which is a file that is wrong the first time an item is
fixed and says nothing about it. The rules instead:

  * the summary table is the authority on what is live at all -- a struck item
    is removed from it, so anything absent is already accounted for;
  * a row is OPEN unless its Item cell says `**fixed**`;
  * a `##` heading is structural if it starts `Tier`, `Raised` or `Filing
    these`, and an item otherwise -- which is how the unnumbered entries (the
    CDPATH one) are carried without naming them here;
  * a group heading is emitted only when something under it survives, with its
    own intro prose, so an item keeps the context of when it was raised;
  * an open number with no `###` section of its own still gets a stub, because
    silently dropping a number is how a backlog loses an item.

    python3 ops/open-backlog.py            # rewrite still_to_do.md
    python3 ops/open-backlog.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import datetime
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "ops" / "records" / "backlog.md"
TARGET = ROOT / "ops" / "records" / "still_to_do.md"

# A `##` heading that opens a group rather than naming an item.
STRUCTURAL = re.compile(r"^## (Tier |Raised |Filing these)")
ROW = re.compile(r"^\| (\d+) \| ([^|]+) \| (.*) \| ([^|]*) \|\s*$")


def heading_number(text: str) -> int | None:
    """The item number a `### 8. ...` heading carries, if it carries one."""
    match = re.match(r"^### (\d+)\.", text)
    return int(match.group(1)) if match else None


def build(lines: list[str], today: str) -> str:
    rows = [(int(m.group(1)), m.group(2).strip(), m.group(3).strip(), line)
            for line in lines if (m := ROW.match(line))]
    # `**fixed**` in the Item cell is the only marker; struck items are gone
    # from the table altogether, so absence needs no separate list here.
    open_rows = [r for r in rows if "**fixed**" not in r[2]]
    open_numbers = {r[0] for r in open_rows}

    heads: list[tuple[int, int, str]] = []
    for i, line in enumerate(lines):
        if line.startswith("### "):
            heads.append((i, 3, line))
        elif line.startswith("## "):
            heads.append((i, 2, line))
    spans = [(i, lvl, txt, heads[j + 1][0] if j + 1 < len(heads) else len(lines))
             for j, (i, lvl, txt) in enumerate(heads)]

    out = [
        "# Still to do\n\n",
        f"The open items from [`backlog.md`](backlog.md), extracted {today} -- everything\n"
        "not marked **fixed** in its summary table and not on its struck list.\n\n",
        "This is a *copy*, not a replacement. `backlog.md` remains the record: it is\n"
        "append-only, it keeps the fixed and struck items with the evidence that closed\n"
        "them, and the item numbers are stable there. Nothing here has been reworded; if\n"
        "the two disagree, `backlog.md` is right.\n\n",
        "Generated by `ops/open-backlog.py` (`just still-to-do`) -- regenerate rather\n"
        "than edit in place.\n\n",
    ]
    out += [line for line in lines if line.startswith(("| # |", "| --- |"))][:2]
    out += [r[3] for r in open_rows]
    out.append("\n*Numbers are `backlog.md`'s, so they are stable and have gaps.*\n\n---\n\n")

    seen: set[int] = set()
    group: tuple[int, int] | None = None
    emitted = False
    for i, lvl, txt, end in spans:
        if lvl == 2:
            if STRUCTURAL.match(txt):
                group, emitted = (i, end), False
            elif txt.startswith("## Filing these"):
                group = None
            else:                                   # an unnumbered item section
                out.append("".join(lines[i:end]))
                group, emitted = None, False
            continue
        number = heading_number(txt)
        if number in open_numbers:
            if group and not emitted:
                start, gend = group
                first = next((s[0] for s in spans if s[0] > start and s[1] == 3), gend)
                out.append("".join(lines[start:first]))
                emitted = True
            out.append("".join(lines[i:end]))
            seen.add(number)

    # An open number the body never sectioned: keep it, and say why it is thin.
    for number, repo, item, _ in open_rows:
        if number in seen:
            continue
        title = item.split(":")[0].split(" -- ")[0].strip().rstrip(".")
        out.append(
            f"---\n\n## {number}. {title} -- table row only\n\n"
            f"**Repo:** {repo}\n\n"
            "`backlog.md` never carried a section for this one; the summary row at the\n"
            "top of this file is the whole of it. Kept here so the number is not\n"
            "silently dropped.\n"
        )
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if the file is out of date")
    args = parser.parse_args()

    lines = SOURCE.read_text().splitlines(keepends=True)
    # The date is the one line that changes without the backlog changing, so
    # --check reuses the existing one rather than reporting drift every day.
    today = str(datetime.date.today())
    if args.check and TARGET.exists():
        if match := re.search(r"extracted (\d{4}-\d\d-\d\d)", TARGET.read_text()):
            today = match.group(1)

    wanted = build(lines, today)
    if args.check:
        current = TARGET.read_text() if TARGET.exists() else ""
        if current == wanted:
            print(f"{TARGET.name} is current")
            return 0
        print(f"{TARGET.name} is out of date -- run `just still-to-do`", file=sys.stderr)
        return 1

    TARGET.write_text(wanted)
    count = sum(1 for line in wanted.splitlines() if ROW.match(line))
    print(f"wrote {TARGET.relative_to(ROOT)}: {count} open items")
    return 0


if __name__ == "__main__":
    sys.exit(main())
